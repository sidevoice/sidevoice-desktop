//! The mobile app's native projects (`mobile/tauri/gen/android`, `mobile/tauri/gen/apple`), generator model G-a (design D.4): the
//! Tauri CLI generates them and nothing in them is edited by hand, so every customisation lives in what the CLI reads
//! (mobile/tauri/tauri.conf.json, mobile/tauri/Info.ios.plist, the Android library of mobile/tauri/plugin, the icon sources in
//! mobile/tauri/app-icon) and the committed projects are exactly what this command writes.
//!
//! - `mobile generate android|ios`: the project made anew (the old one removed, so a file the template no longer has
//!   goes too), then the icons derived from the sources (`tauri icon` writes them into the projects that exist). Runs
//!   in mobile/tauri/, where tauri.conf.json is. The iOS project needs macOS and XcodeGen. The CLI's targets are not
//!   installed here (`--skip-targets-install`): mobile/rust-toolchain.toml names them. The iOS project also gets the
//!   localized permission texts (mobile/tauri/ios/<language>.lproj/InfoPlist.strings) and the privacy manifest
//!   (mobile/tauri/PrivacyInfo.xcprivacy), which the CLI has no setting for: they are put where the project reads its sources
//!   before the CLI makes the project, and the project is read for them after.
//! - `mobile generated android|ios`: `generate`, then the committed project must be what it wrote (CI, every pull
//!   request): a difference means an input or the CLI changed and the project was not regenerated and committed.
//! - `mobile build android|ios`: the app as a pull request builds it, unsigned: Android's universal release APK (arm64-v8a and armeabi-v7a), and
//!   the iOS app for the simulator (no signing, so no secret), into dist/; told what build it is (`host.build`: a nightly on CI, `dev` elsewhere, `SIDEVOICE_BUILD_CHANNEL` overrides; mobile/tauri/build.rs). Needs the SDK and NDK, or macOS with Xcode. The
//!   Android APK is also checked for 16 KB pages, which Google Play requires (`mobile check-16kb [APK]` is that check alone),
//!   and the iOS app for what it declares to Apple: the privacy manifest and the export compliance (`mobile check-ios [APP]`
//!   is that check alone, ios.rs).
//! - `mobile screenshots ios`: the app `mobile build ios` left in dist/ run on an iPhone Pro Max simulator, in light and dark:
//!   screenshots and the app's log into dist/simulator/ (platform/ios_simulator.rs). Needs macOS with Xcode.
//! - `mobile lint android|ios`: Clippy, warnings denied, over the mobile crates for their target (they are empty on a
//!   computer: `#![cfg(mobile)]`).
//! - `mobile sign android`: sign.rs.
//! - `mobile test android`: the Kotlin library's JVM unit tests, in the generated project (after a build).
//! - `mobile testflight --build-number N`: the signed iOS archive uploaded to TestFlight, by hand from main (testflight.rs).

