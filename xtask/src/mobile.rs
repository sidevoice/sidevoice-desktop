/// Where the Android project takes the native libraries it packages beside the app's own (`jniLibs/<abi>/`; git ignores
/// the `.so` files there).
const ANDROID_LIBS: &str = "mobile/tauri/gen/android/app/src/main/jniLibs";

/// Where the iOS project takes the frameworks it embeds (`bundle.iOS.frameworks` in mobile/tauri/tauri.conf.json; ignored by
/// git).
const IOS_FRAMEWORKS: &str = "mobile/tauri/frameworks";

/// The native libraries of the engine that the app packages, fetched by the engine's own `cargo xtask mobile-libs
/// <android|ios>` at the commit Cargo.lock pins: the archives its pins name, checked against their digests and unpacked,
/// with no engine build (sidevoice-engine's README, "Android" and "iOS"). Android's (sherpa-onnx's and ONNX Runtime's
/// `.so`) go to the project's `jniLibs/<abi>/`; iOS's two xcframeworks (`sherpa-onnx` and `onnxruntime`, one shared
/// runtime) to mobile/tauri/frameworks/, with each target's slices beside them.
pub fn engine_libs(name: &str, target: &str) -> Result<EngineLibs> {
    Ok(engine_libs_of(name, &[target])?.remove(0))
}

/// [`engine_libs`] for each of `targets`, fetched once.
fn engine_libs_of(name: &str, targets: &[&str]) -> Result<Vec<EngineLibs>> {
    let android = project(name)?.cli == "android";
    let dir = repo().join(if android { ANDROID_LIBS } else { IOS_FRAMEWORKS });
    let dir_text = dir.to_string_lossy().into_owned();
    crate::checks::engine_xtask(&["mobile-libs", if android { "android" } else { "ios" }, &dir_text])?.run()?;
    let mut all = Vec::new();
    for target in targets {
        let (sherpa, onnxruntime) = if android {
            (dir.join(android_abi(target)?), None)
        } else {
            (dir.join(format!("lib-{target}")), Some(dir.join(format!("frameworks-{target}"))))
        };
        for linked in std::iter::once(&sherpa).chain(onnxruntime.as_ref()) {
            ensure(linked.is_dir(), format!("{}: the engine's libraries have nothing for {target}", linked.display()))?;
        }
        all.push(EngineLibs { sherpa, onnxruntime });
    }
    Ok(all)
}

/// The Rust targets the Android app is built for (D-ANDROID-ABIS: 64-bit and 32-bit ARM phones; x86_64, the emulator, is
/// built by hand), and each one's ABI directory.
const ANDROID_TARGETS: [&str; 2] = ["aarch64-linux-android", "armv7-linux-androideabi"];

fn android_abi(target: &str) -> Result<&'static str> {
    match target {
        "aarch64-linux-android" => Ok("arm64-v8a"),
        "armv7-linux-androideabi" => Ok("armeabi-v7a"),
        "x86_64-linux-android" => Ok("x86_64"),
        other => Err(format!("no Android ABI for {other}")),
    }
}

/// What an app build of one target links against: `SHERPA_ONNX_LIB_DIR`, and on iOS `ONNXRUNTIME_FRAMEWORK_DIR` (the
/// engine's `build.rs` links the shared ONNX Runtime from it).
pub struct EngineLibs {
    pub sherpa: PathBuf,
    pub onnxruntime: Option<PathBuf>,
}

impl EngineLibs {
    /// The variables the app's cargo reads, with their values.
    fn vars(&self) -> Vec<(&'static str, &Path)> {
        let mut vars = vec![("SHERPA_ONNX_LIB_DIR", self.sherpa.as_path())];
        vars.extend(self.onnxruntime.as_deref().map(|dir| ("ONNXRUNTIME_FRAMEWORK_DIR", dir)));
        vars
    }

    /// Sets them on `cmd`.
    pub fn apply(&self, mut cmd: Cmd) -> Cmd {
        for (key, value) in self.vars() {
            cmd = cmd.env(key, value);
        }
        cmd
    }
}

/// The engine's libraries for one app build, held where every cargo the build runs finds them: in this process's
/// environment for the Tauri CLI's own cargo, and in the repository's cargo config (`.cargo/config.toml`, `[env]`) for
/// the cargo the native project runs again from inside its build (the Xcode build phase, Gradle's `rust` task). The Tauri
/// CLI hands those only the variables named `TAURI*`, `WRY*`, `CARGO_*` or `RUST_*`, and `PATH` and `TMPDIR`
/// (`env_vars` in its `mobile` module), so `SHERPA_ONNX_LIB_DIR` and `ONNXRUNTIME_FRAMEWORK_DIR` would not reach them:
/// their `sherpa-onnx-sys` would then download its own copy, unchecked, and on iOS lose the target's library (`library
/// 'sherpa-onnx-c-api' not found`), whatever a build cache happened to keep. The config is given back as it was when this
/// is dropped, failed build or not.
pub struct AppBuildLibs {
    /// What the build's first target links against (iOS builds one target; Android's are in the cargo config).
    pub libs: EngineLibs,
    config: PathBuf,
    original: Option<Vec<u8>>,
}

impl AppBuildLibs {
    /// [`engine_libs`] for each of `targets`, written into the cargo config for the length of the build.
    ///
    /// iOS (one target) is given as `[env]` variables. Android's build runs one cargo per ABI under one Gradle build, and
    /// `[env]` has no per-target form, so each target gets cargo's build-script override for the `sherpa-onnx` link
    /// (`[target.<triple>.sherpa-onnx]`): `sherpa-onnx-sys`'s build script is not run, and the target links the engine's
    /// shared libraries of its own ABI, which `jniLibs/<abi>/` already holds for Gradle to package.
    pub fn hold(name: &str, targets: &[&str]) -> Result<AppBuildLibs> {
        let android = project(name)?.cli == "android";
        let mut all = engine_libs_of(name, targets)?;
        let config = repo().join(".cargo/config.toml");
        let original = fs::read(&config).ok();
        let mut text = original.as_deref().map(String::from_utf8_lossy).unwrap_or_default().into_owned();
        text.push_str(
            "\n# Written by `cargo xtask mobile` for one app build, and taken out after it (xtask/src/mobile.rs, AppBuildLibs).\n",
        );
        if android {
            ensure(!text.contains(".sherpa-onnx]"), format!("{}: overrides sherpa-onnx already", config.display()))?;
            for (target, libs) in targets.iter().zip(&all) {
                let dir =
                    serde_json::to_string(&format!("native={}", libs.sherpa.display())).map_err(|e| e.to_string())?;
                text.push_str(&format!(
                    "[target.{target}.sherpa-onnx]\nrustc-link-search = [{dir}]\nrustc-link-lib = [\"dylib=sherpa-onnx-c-api\", \"dylib=onnxruntime\"]\n"
                ));
            }
        } else {
            ensure(!text.contains("\n[env]"), format!("{}: has an [env] table already", config.display()))?;
            text.push_str("[env]\n");
            for (key, value) in all[0].vars() {
                let value = serde_json::to_string(&value.to_string_lossy()).map_err(|e| e.to_string())?;
                text.push_str(&format!("{key} = {value}\n"));
            }
            // The oldest iOS the app runs on, for the C and C++ the build scripts compile (whisper.cpp, aws-lc): without
            // it they target the SDK's own version, and an availability check (`@available(iOS 18, *)`) is then compiled
            // as always true, so the app calls what an older iOS lacks.
            let minimum = serde_json::to_string(&ios_deployment_target()?).map_err(|e| e.to_string())?;
            text.push_str(&format!("IPHONEOS_DEPLOYMENT_TARGET = {minimum}\n"));
        }
        write(&config, text)?;
        Ok(AppBuildLibs { libs: all.remove(0), config, original })
    }
}

/// The oldest iOS the app runs on: `bundle.iOS.minimumSystemVersion` in mobile/tauri/tauri.conf.json, which the Xcode
/// project's deployment target is generated from.
fn ios_deployment_target() -> Result<String> {
    let path = repo().join("mobile/tauri/tauri.conf.json");
    let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    let config: serde_json::Value = serde_json::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))?;
    config["bundle"]["iOS"]["minimumSystemVersion"]
        .as_str()
        .map(str::to_owned)
        .ok_or_else(|| format!("{}: no bundle.iOS.minimumSystemVersion", path.display()))
}

impl Drop for AppBuildLibs {
    fn drop(&mut self) {
        let _ = match &self.original {
            Some(bytes) => fs::write(&self.config, bytes),
            None => fs::remove_file(&self.config),
        };
    }
}

/// `mobile build android|ios`: the app as a pull request builds it, unsigned, into dist/.
pub fn build(name: &str) -> Result<()> {
    let dist = repo().join("dist");
    mkdir(&dist)?;
    match project(name)?.cli {
        "android" => {
            let libs = AppBuildLibs::hold(name, &ANDROID_TARGETS)?;
            build_tauri(&["android", "build", "--apk", "--target", "aarch64", "--target", "armv7", "--ci"])?.run()?;
            drop(libs);
            let apk = repo().join("mobile/tauri/gen/android").join(UNSIGNED_APK);
            let to = unsigned_apk();
            fs::copy(&apk, &to).map_err(|e| format!("{}: {e}", apk.display()))?;
            check::check_16kb(&to)
        }
        _ => {
            let libs = AppBuildLibs::hold(name, &["aarch64-apple-ios-sim"])?;
            libs.libs.apply(build_tauri(&["ios", "build", "--target", "aarch64-sim", "--no-sign", "--ci"])?).run()?;
            drop(libs);
            let build = repo().join("mobile/tauri/gen/apple/build");
            let app = find_app(&build, 3).ok_or_else(|| format!("no .app below {}", build.display()))?;
            ios::check_app(&app)?;
            // The app is a directory with symbolic links in it: zip keeps them (`-y`).
            Cmd::new("zip")
                .args(["-qry"])
                .arg(dist.join("Sidevoice-ios-simulator.zip"))
                .arg(app.file_name().ok_or("an .app has a name")?)
                .dir(app.parent().ok_or("an .app has a parent")?)
                .run()
        }
    }
}

/// The first `.app` directory below `dir`, at most `depth` levels down.
fn find_app(dir: &Path, depth: usize) -> Option<PathBuf> {
    let mut entries: Vec<PathBuf> = fs::read_dir(dir).ok()?.filter_map(|e| e.ok().map(|e| e.path())).collect();
    entries.sort();
    entries.iter().find(|p| p.is_dir() && p.extension().is_some_and(|e| e == "app")).cloned().or_else(|| {
        (depth > 1).then(|| entries.iter().filter(|p| p.is_dir()).find_map(|p| find_app(p, depth - 1))).flatten()
    })
}

