//! The plugin's commands through Tauri's own authorization, not a stand-in for it: the mock runtime is given the ACL that
//! the plugin's permission files and a capability (the room window's, as an app writes it) make, and the IPC enforces
//! it. A command from a window the capability does not name, or from a remote origin, never reaches the command.

use std::collections::BTreeMap;
use std::sync::Arc;

use serde_json::{json, Value};
use sidevoice_app_core::app::{
    AlwaysAdmit, AppHost, EventSink, Hooks, HostConfig, KeyError, PageGeneration, ProviderKeys,
};
use tauri::ipc::{CallbackFn, InvokeBody, RuntimeAuthority};
use tauri::test::{get_ipc_response, mock_builder, mock_context, noop_assets, MockRuntime, INVOKE_KEY};
use tauri::webview::InvokeRequest;
use tauri::{AppHandle, Manager, Webview, WebviewUrl, WebviewWindow, WebviewWindowBuilder};
use tauri_utils::acl::capability::Capability;
use tauri_utils::acl::manifest::Manifest;
use tauri_utils::acl::manifest::PermissionFile;
use tauri_utils::acl::resolved::Resolved;
use tauri_utils::platform::Target;

use crate::platform::origin::APP_ORIGIN;
use crate::{inventory, Pages, PLUGIN};

struct Nowhere;

impl EventSink for Nowhere {
    fn event(&self, _page: PageGeneration, _event: Value) {}
}

impl ProviderKeys for Nowhere {
    fn valid(&self, _provider: &str) -> bool {
        true
    }

    fn read(&self, _provider: &str) -> Result<Option<String>, KeyError> {
        Ok(None)
    }

    fn write(&self, _provider: &str, _key: Option<&str>) -> Result<(), KeyError> {
        Ok(())
    }
}

/// The plugin's manifest, from the permission files it commits, and a capability granting the inventory to `windows`.
fn authority(windows: &[&str]) -> RuntimeAuthority {
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("permissions/autogenerated/commands");
    let files: Vec<PermissionFile> = std::fs::read_dir(&dir)
        .unwrap()
        .map(|file| toml::from_str(&std::fs::read_to_string(file.unwrap().path()).unwrap()).unwrap())
        .collect();
    let acl = BTreeMap::from([(PLUGIN.to_owned(), Manifest::new(files, None))]);
    let permissions: Vec<String> = inventory().into_iter().map(|entry| entry.permission).collect();
    let room: Capability = serde_json::from_value(json!({
        "identifier": "room",
        "windows": windows,
        "permissions": permissions,
    }))
    .unwrap();
    let resolved = Resolved::resolve(&acl, BTreeMap::from([("room".to_owned(), room)]), Target::current()).unwrap();
    RuntimeAuthority::new(acl, resolved)
}

fn request(command: &str, body: Value, origin: &str) -> InvokeRequest {
    InvokeRequest {
        cmd: format!("plugin:{PLUGIN}|{command}"),
        callback: CallbackFn(0),
        error: CallbackFn(1),
        url: origin.parse().unwrap(),
        body: InvokeBody::Json(body),
        headers: Default::default(),
        invoke_key: INVOKE_KEY.to_string(),
    }
}

/// The app's answer to who the page is, as the desktop gives it: the window called `room-1` is the current room window,
/// and it shows `own`, the origin the app's pages are served from.
fn the_page(
    own: &'static str,
) -> impl Fn(&AppHandle<MockRuntime>, &Webview<MockRuntime>) -> Result<(), String> + Send + Sync + 'static {
    move |_app, webview| {
        if webview.label() != "room-1" {
            return Err("not the room window".into());
        }
        let url = webview.url().map_err(|why| why.to_string())?;
        if format!("{}://{}", url.scheme(), url.host_str().unwrap_or_default()) != own {
            return Err("not the app's own page".into());
        }
        Ok(())
    }
}

/// An app with the plugin, the ACL above, a real host, and windows called `room-1` and `call-controls`.
struct Fixture {
    app: tauri::App<MockRuntime>,
    room: WebviewWindow<MockRuntime>,
    card: WebviewWindow<MockRuntime>,
    root: std::path::PathBuf,
}

fn fixture(name: &str) -> Fixture {
    fixture_where(name, &["room-*"], APP_ORIGIN)
}

/// [`fixture`] with the capability naming `windows`, and `own` the origin the app says its pages are served from.
fn fixture_where(name: &str, windows: &[&str], own: &'static str) -> Fixture {
    let root = std::env::temp_dir().join(format!("sidevoice-app-tauri-{name}-{}", std::process::id()));
    let mut context = mock_context(noop_assets());
    *context.runtime_authority_mut() = authority(windows);
    let pages = Pages::default();
    let app = mock_builder().plugin(crate::init(the_page(own), pages.clone())).build(context).unwrap();
    let hooks = Hooks { admission: Arc::new(AlwaysAdmit), events: Arc::new(pages), keys: Arc::new(Nowhere) };
    app.manage(AppHost::new(
        HostConfig { model_root: root.clone() },
        tauri::async_runtime::handle().inner().clone(),
        hooks,
    ));
    let room = WebviewWindowBuilder::new(&app, "room-1", WebviewUrl::App("index.html".into())).build().unwrap();
    let card = WebviewWindowBuilder::new(&app, "call-controls", WebviewUrl::App("index.html".into())).build().unwrap();
    Fixture { app, room, card, root }
}

/// The origin the app's own pages are served from, as the window under test reports it.
fn local(window: &WebviewWindow<MockRuntime>) -> String {
    let url = window.url().unwrap();
    format!("{}://{}", url.scheme(), url.host_str().unwrap())
}

#[test]
fn the_room_window_on_the_apps_origin_reaches_the_commands_the_capability_names() {
    let f = fixture("room");
    // An engine command, which asks the caller first: the current room window on the app's origin is the page.
    let answered =
        get_ipc_response(&f.room, request("engine_progress", json!({"job": "none"}), &local(&f.room))).unwrap();
    assert_eq!(answered.deserialize::<Value>().unwrap(), Value::Null);
    let _ = std::fs::remove_dir_all(&f.root);
    drop(f.app);
}

#[test]
fn the_call_controls_card_and_a_window_nobody_named_are_refused_every_command() {
    let f = fixture("card");
    let stray = WebviewWindowBuilder::new(&f.app, "main", WebviewUrl::App("index.html".into())).build().unwrap();
    for command in inventory().into_iter().map(|entry| entry.command) {
        for window in [&f.card, &stray] {
            let refused = get_ipc_response(window, request(&command, json!({}), &local(window))).unwrap_err();
            let message = refused.to_string();
            assert!(message.contains("not allowed"), "{command} from {}: {message}", window.label());
        }
    }
    let _ = std::fs::remove_dir_all(&f.root);
}

#[test]
fn a_remote_origin_is_refused_even_in_the_room_window() {
    let f = fixture("remote");
    for command in inventory().into_iter().map(|entry| entry.command) {
        let refused = get_ipc_response(&f.room, request(&command, json!({}), "https://evil.example")).unwrap_err();
        assert!(refused.to_string().contains("not allowed"), "{command}: {refused}");
    }
    let _ = std::fs::remove_dir_all(&f.root);
}

/// Every engine command with arguments the host would accept, so that a refusal below is the caller check's and not the
/// arguments'.
fn engine_calls() -> Vec<(&'static str, Value)> {
    let calls = vec![
        ("engine_capabilities", json!({})),
        ("engine_installed", json!({})),
        ("engine_install", json!({"model": "m", "build": null, "engine": null, "job": "j"})),
        ("engine_progress", json!({"job": "j"})),
        ("engine_cancel", json!({"job": "j"})),
        ("engine_uninstall", json!({"model": "m"})),
        ("engine_memory", json!({})),
        ("engine_catalogs", json!({})),
        ("engine_set_credential", json!({"provider": "openai", "key": "k"})),
        ("engine_has_credential", json!({"provider": "openai"})),
        ("engine_test_credential", json!({"provider": "openai", "key": "k"})),
        ("engine_refresh", json!({"provider": "openai"})),
    ];
    let listed: Vec<String> =
        inventory().into_iter().map(|entry| entry.command).filter(|command| command.starts_with("engine_")).collect();
    assert_eq!(calls.iter().map(|(command, _)| (*command).to_owned()).collect::<Vec<_>>(), listed);
    calls
}

#[test]
fn an_engine_command_refuses_a_stale_room_the_card_and_another_window_even_where_the_capability_names_them() {
    // A capability names windows by label, so it cannot tell the current room window from a replaced one: this one names
    // every window, and what stands between the engine and them is the caller check alone.
    let f = fixture_where("caller", &["*"], APP_ORIGIN);
    let build = |label| WebviewWindowBuilder::new(&f.app, label, WebviewUrl::App("index.html".into())).build().unwrap();
    let (stale, other) = (build("room-0"), build("main"));
    for (command, body) in engine_calls() {
        for window in [&stale, &f.card, &other] {
            let refused = get_ipc_response(window, request(command, body.clone(), &local(window))).unwrap_err();
            assert_eq!(
                refused,
                json!({"key": "bad_request", "message": "not the room window"}),
                "{command} from {}",
                window.label()
            );
        }
    }
    let _ = std::fs::remove_dir_all(&f.root);
}

#[test]
fn an_engine_command_refuses_the_current_room_window_showing_another_origin() {
    // The app says its own pages are served from an origin other than the one the room window shows.
    let f = fixture_where("origin", &["room-*"], "https://app.example");
    for (command, body) in engine_calls() {
        let refused = get_ipc_response(&f.room, request(command, body, &local(&f.room))).unwrap_err();
        assert_eq!(refused, json!({"key": "bad_request", "message": "not the app's own page"}), "{command}");
    }
    let _ = std::fs::remove_dir_all(&f.root);
}
