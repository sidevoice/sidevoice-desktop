//! ACL.md as data: who may call what, one [`Entry`] per command, for the tests that keep it, the permission files and an
//! app's capabilities to one list.

/// One row of ACL.md.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Entry {
    pub command: String,
    /// The permission an app grants to let a window invoke it: `sidevoice-app-tauri:allow-<command>`.
    pub permission: String,
    /// Where the app grants it.
    pub window: String,
    /// What the command asks of who invoked it.
    pub caller: String,
    pub arguments: String,
    pub tells_the_page: String,
    /// Whether the call controls card's window may invoke it.
    pub card: String,
}

/// Every row of ACL.md's table, in its order.
pub fn inventory() -> Vec<Entry> {
    include_str!("../ACL.md")
        .lines()
        .filter(|line| line.starts_with("| `"))
        .map(|line| {
            let cells: Vec<String> =
                line.trim().trim_matches('|').split('|').map(|cell| cell.trim().to_owned()).collect();
            let unquoted = |cell: &str| cell.trim_matches('`').to_owned();
            assert_eq!(cells.len(), 7, "ACL.md: a row has seven cells: {line}");
            Entry {
                command: unquoted(&cells[0]),
                permission: unquoted(&cells[1]),
                window: cells[2].clone(),
                caller: cells[3].clone(),
                arguments: cells[4].clone(),
                tells_the_page: cells[5].clone(),
                card: cells[6].clone(),
            }
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;

    use super::*;
    use crate::{COMMANDS, PLUGIN};

    #[test]
    fn the_inventory_lists_each_command_once_and_only_those() {
        let listed: Vec<String> = inventory().into_iter().map(|entry| entry.command).collect();
        let unique: BTreeSet<&str> = listed.iter().map(String::as_str).collect();
        assert_eq!(unique.len(), listed.len(), "a command twice: {listed:?}");
        assert_eq!(unique, COMMANDS.iter().copied().collect::<BTreeSet<_>>());
    }

    #[test]
    fn each_command_is_granted_by_its_own_permission_to_the_room_and_never_to_the_card() {
        for entry in inventory() {
            let permission = format!("{PLUGIN}:allow-{}", entry.command.replace('_', "-"));
            assert_eq!(entry.permission, permission, "{}", entry.command);
            assert_eq!(entry.window, "room", "{}", entry.command);
            assert_eq!(entry.card, "no", "{}", entry.command);
            assert_eq!(entry.caller, "room page", "{}", entry.command);
            assert!(!entry.arguments.is_empty() && !entry.tells_the_page.is_empty(), "{}", entry.command);
        }
    }

    #[test]
    fn a_permission_is_written_for_each_command_and_for_no_other() {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("permissions/autogenerated/commands");
        let written: BTreeSet<String> = std::fs::read_dir(&dir)
            .unwrap_or_else(|e| panic!("{}: {e}", dir.display()))
            .map(|file| file.unwrap().file_name().to_string_lossy().trim_end_matches(".toml").to_owned())
            .collect();
        assert_eq!(written, COMMANDS.iter().map(|command| (*command).to_owned()).collect::<BTreeSet<_>>());
        for command in COMMANDS {
            let text = std::fs::read_to_string(dir.join(format!("{command}.toml"))).unwrap();
            assert!(text.contains(&format!("identifier = \"allow-{}\"", command.replace('_', "-"))), "{command}");
            assert!(text.contains(&format!("commands.allow = [\"{command}\"]")), "{command}");
        }
    }
}
